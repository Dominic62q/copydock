"""Turn a Compose project into a bundle: images + offline compose file + manifest + checksums.

Bundle layout (inside <name>-<version>-<os>-<arch>.tar.gz, under one top-level folder):

    manifest.json        packing list (see manifest.py)
    bundle.conf          the same facts as KEY='value' lines, for install.sh
    checksums.txt        sha256 of every other file, in `sha256sum -c` format
    compose.yaml         rewritten: no builds, pull_policy never, bind mounts under files/
    config/environment.example   names of the settings the server must provide
    files/               bind-mounted project files
    images/images.tar    every image, saved with `docker save`
    install.sh           installer (runs on the server; needs only Docker)
    README.md
"""

from __future__ import annotations

import copy
import hashlib
import re
import shutil
import tarfile
import tempfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

import yaml

from copydock import __version__, docker, ui
from copydock.analysis import Finding, analyze, find_compose_file, load_config
from copydock.errors import CopyDockError
from copydock.manifest import ImageEntry, Manifest

_SAFE_VERSION = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
_TEMPLATES = Path(__file__).parent / "templates"
_COMPOSE_HEADER = (
    "# Generated by CopyDock. Images are pre-loaded; nothing is built or pulled.\n"
    "# Settings such as ${POSTGRES_PASSWORD} are read from .env on the server.\n"
)


@dataclass
class PackageResult:
    archive: Path
    sidecar: Path
    size: int
    sha256: str
    manifest: Manifest
    findings: list[Finding]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def render_compose(
    config: dict, refs: dict[str, str], root: Path
) -> tuple[dict, dict[str, Path]]:
    """Rewrite a resolved compose config for offline use.

    Returns the new config and the files to copy: {path inside bundle: source path}.
    """
    data = copy.deepcopy(config)
    root = root.resolve()
    copies: dict[str, Path] = {}
    for name, svc in (data.get("services") or {}).items():
        svc.pop("build", None)
        svc["image"] = refs[name]
        svc["pull_policy"] = "never"
        for vol in svc.get("volumes") or []:
            if vol.get("type") != "bind":
                continue
            source = Path(vol["source"])
            dest = Path("files") / source.resolve().relative_to(root)
            copies[dest.as_posix()] = source
            vol["source"] = f"./{dest.as_posix()}"
    return data, copies


def environment_template(app: str, names: list[str]) -> str:
    lines = [
        f"# Settings for {app}. Copy this file to .env on the server and fill in each value.",
        "# Never commit .env or share it. Keep it readable only by you: chmod 600 .env",
        "",
    ]
    lines += [f"{n}=" for n in names] or ["# (this app needs no settings)"]
    return "\n".join(lines) + "\n"


def bundle_readme(app: str, version: str, platform: str, bundle_dir: str) -> str:
    return f"""# {app} {version} ({platform})

Built with CopyDock {__version__}. This folder installs {app} on a Linux server that has
Docker and Docker Compose. It does not download anything.

## Install

    ./install.sh              # checks the server, asks for settings, loads images, starts the app
    ./install.sh --check      # only verify the bundle and check the server; changes nothing

Settings are stored in .env next to install.sh (mode 600). To prepare them yourself, copy
config/environment.example to .env and fill in every value.

## What is inside

- compose.yaml: the app definition. Images are pre-loaded, so nothing is built or pulled.
- images/images.tar: all container images.
- config/environment.example: the settings the server must provide.
- manifest.json, bundle.conf and checksums.txt: what is in this bundle and how to verify it.

## By hand (if you prefer not to use install.sh)

    sha256sum -c checksums.txt
    docker load -i images/images.tar
    cp config/environment.example .env     # then fill in every value, and: chmod 600 .env
    docker compose up -d --pull never

Folder: {bundle_dir}
"""


_CONF_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_CONF_REF = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/:@-]*$")


def bundle_conf(m: Manifest) -> str:
    """Facts the installer needs, as KEY='value' lines it can source. install.sh runs on servers
    with no JSON tools, so it reads this instead of manifest.json.

    Every value is checked against a strict pattern, because the installer sources this file.
    """
    for name in m.required_env:
        if not _CONF_NAME.match(name):
            raise CopyDockError(f"Setting name '{name}' has characters v1 does not support.")
    for img in m.images:
        if not _CONF_REF.match(img.reference):
            raise CopyDockError(f"Image name '{img.reference}' has characters v1 does not support.")
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", m.app_name):
        raise CopyDockError(f"Project name '{m.app_name}' must be lowercase letters, digits, - or _.")
    pairs = {
        "APP_NAME": m.app_name,
        "APP_VERSION": m.app_version,
        "PLATFORM": m.platform,
        "REQUIRED_PORTS": " ".join(str(p) for p in m.required_ports),
        "REQUIRED_ENV": " ".join(m.required_env),
        "IMAGES": " ".join(i.reference for i in m.images),
        "IMAGES_ARCHIVE": m.images_archive,
    }
    return "# Generated by CopyDock. Read by install.sh.\n" + "".join(
        f"{k}='{v}'\n" for k, v in pairs.items()
    )


def _checksums(root: Path) -> dict[str, str]:
    sums = {}
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        sums[path.relative_to(root).as_posix()] = sha256_file(path)
    return sums


def _make_archive(staging: Path, bundle_dir: str, archive: Path) -> None:
    with tarfile.open(archive, "w:gz") as tar:
        for path in sorted(staging.rglob("*")):
            info = tar.gettarinfo(str(path), f"{bundle_dir}/{path.relative_to(staging).as_posix()}")
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mode = 0o755 if path.is_dir() or path.name == "install.sh" else 0o644
            if path.is_file():
                with path.open("rb") as f:
                    tar.addfile(info, f)
            else:
                tar.addfile(info)


def package_project(
    project: Path,
    compose_name: str | None,
    platform: str | None,
    output: Path,
    app_version: str,
    allow_secret_files: bool = False,
) -> PackageResult:
    project = project.resolve()
    if not _SAFE_VERSION.match(app_version):
        raise CopyDockError(
            f"Invalid --app-version '{app_version}'. Use letters, digits, '.', '_' and '-'."
        )

    with ui.step("Reading the compose project") as s:
        compose_path = find_compose_file(project, compose_name)
        config = load_config(project, compose_path)
        report = analyze(config, compose_path.read_text(), project, compose_path.name)
        blocking = list(report.errors)
        if not allow_secret_files:
            blocking += [f for f in report.warnings if f.code == "secret-file"]
        if blocking:
            raise CopyDockError(
                "This project cannot be packaged yet:\n"
                + "\n".join(f"  - {f.message}" for f in blocking)
                + ("\n\nTo bundle secret-looking files anyway, pass --include-secret-files."
                   if any(f.code == "secret-file" for f in blocking) else "")
            )  # fmt: skip
        s.detail = f"{len(report.services)} services"

    with ui.step("Connecting to Docker") as s:
        local = docker.server_platform()
        platform = platform or local
        if platform not in docker.SUPPORTED_PLATFORMS:
            raise CopyDockError(
                f"Unsupported platform '{platform}'. Choose one of: "
                + ", ".join(docker.SUPPORTED_PLATFORMS)
            )
        s.detail = f"target {platform}"
        if platform != local:
            s.notes.append(f"This machine is {local}: building for {platform} runs under "
                           "emulation and can be slow.")  # fmt: skip

    app = config.get("name") or project.name.lower()
    refs = {s.name: s.image for s in report.services if s.image}
    if len(refs) != len(report.services):
        raise CopyDockError("Every service needs an `image:` or a `build:`.")

    # One entry per distinct image reference, remembering which services use it.
    plan: dict[str, dict] = {}
    for svc in report.services:
        entry = plan.setdefault(svc.image, {"services": [], "build": None})
        entry["services"].append(svc.name)
        if svc.build_context:
            entry["build"] = config["services"][svc.name]["build"]

    images: list[ImageEntry] = []
    for ref, entry in plan.items():
        built = entry["build"] is not None
        with ui.step(f"{'Building' if built else 'Pulling'} {ref}") as s:
            if built:
                b = entry["build"]
                args = {k: str(v) for k, v in (b.get("args") or {}).items() if v is not None}
                docker.build(ref, Path(b["context"]), b.get("dockerfile", "Dockerfile"),
                             platform, args, b.get("target"))  # fmt: skip
            else:
                docker.pull(ref, platform)
            info = docker.inspect_image(ref)
            got = f"{info.get('Os')}/{info.get('Architecture')}"
            if got != platform:
                raise CopyDockError(
                    f"{ref} is {got}, not {platform}. The image does not support the target "
                    "platform, or a different local copy is shadowing it."
                )
            digests = info.get("RepoDigests") or []
            images.append(ImageEntry(
                reference=ref,
                services=entry["services"],
                image_id=info["Id"],
                # Only registry images have a meaningful digest; local builds have none.
                repo_digest=digests[0] if digests and not built else None,
                built=built,
                size_bytes=info.get("Size", 0),
            ))  # fmt: skip
            s.detail = ui.human_size(info.get("Size", 0))

    bundle_dir = f"{app}-{app_version}-{platform.replace('/', '-')}"
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    archive = output / f"{bundle_dir}.tar.gz"

    with tempfile.TemporaryDirectory(prefix="copydock-") as tmp:
        staging = Path(tmp)
        (staging / "images").mkdir()
        (staging / "config").mkdir()

        with ui.step("Saving images") as s:
            tar_path = staging / "images" / "images.tar"
            docker.save([i.reference for i in images], tar_path)
            s.detail = ui.human_size(tar_path.stat().st_size)

        with ui.step("Writing deployment files") as s:
            data, copies = render_compose(config, refs, project)
            for dest, source in copies.items():
                if not source.exists():
                    raise CopyDockError(f"Bind mount source does not exist: {source}")
                target = staging / dest
                target.parent.mkdir(parents=True, exist_ok=True)
                if source.is_dir():
                    shutil.copytree(source, target)
                else:
                    shutil.copy2(source, target)
            compose_text = _COMPOSE_HEADER + yaml.safe_dump(
                data, sort_keys=False, default_flow_style=False, width=100
            )
            (staging / "compose.yaml").write_text(compose_text)
            (staging / "config" / "environment.example").write_text(
                environment_template(app, report.required_env)
            )
            shutil.copy2(_TEMPLATES / "install.sh", staging / "install.sh")
            (staging / "README.md").write_text(bundle_readme(app, app_version, platform, bundle_dir))
            s.detail = f"{len(copies)} bundled file{'s' * (len(copies) != 1)}"

        with ui.step("Validating offline compose") as s:
            docker.run(
                ["compose", "-f", str(staging / "compose.yaml"), "--project-directory",
                 str(staging), "config", "--no-interpolate", "-q"],
                "Validating the rewritten compose file",
            )  # fmt: skip
            if any("build" in svc for svc in data["services"].values()):
                raise CopyDockError("Internal error: rewritten compose file still has a build.")
            s.detail = "no builds, no pulls"

        with ui.step("Sealing the bundle") as s:
            manifest = Manifest(
                app_name=app,
                app_version=app_version,
                platform=platform,
                created_at=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                copydock_version=__version__,
                images=images,
                required_ports=report.published_ports,
                required_env=report.required_env,
            )
            (staging / "bundle.conf").write_text(bundle_conf(manifest))
            manifest.checksums = _checksums(staging)
            (staging / "manifest.json").write_text(manifest.to_json() + "\n")
            sums = _checksums(staging)
            (staging / "checksums.txt").write_text(
                "".join(f"{digest}  {name}\n" for name, digest in sums.items())
            )
            _make_archive(staging, bundle_dir, archive)
            archive_sha = sha256_file(archive)
            sidecar = archive.with_name(archive.name + ".sha256")
            sidecar.write_text(f"{archive_sha}  {archive.name}\n")
            s.detail = ui.human_size(archive.stat().st_size)

    return PackageResult(
        archive=archive,
        sidecar=sidecar,
        size=archive.stat().st_size,
        sha256=archive_sha,
        manifest=manifest,
        findings=report.findings,
    )
